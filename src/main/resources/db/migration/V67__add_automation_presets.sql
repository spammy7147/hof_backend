create table automation_presets (
    id bigint generated by default as identity,
    account_id bigint not null,
    name varchar(100) not null,
    settings_json text not null,
    entry_count integer not null,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    constraint pk_automation_presets primary key (id),
    constraint uk_automation_presets_account_name unique (account_id, name),
    constraint fk_automation_presets_account foreign key (account_id) references hof_accounts(id) on delete cascade,
    constraint ck_automation_presets_entry_count check (entry_count between 0 and 100)
);
